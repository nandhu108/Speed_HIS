export function MenuIconFor({ name }: { name: string | null }) {
  const Icon = name ? MENU_ICONS[name] : undefined
  if (!Icon) return <span className="inline-block size-1.5 rounded-full bg-current opacity-50" aria-hidden />
  return <Icon className="size-[18px] shrink-0" aria-hidden />
}
