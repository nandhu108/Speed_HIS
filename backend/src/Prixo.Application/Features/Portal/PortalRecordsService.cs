using Microsoft.EntityFrameworkCore;
using Prixo.Application.Common.Interfaces;
using Prixo.Application.Features.Billing;
using Prixo.Application.Features.Emr;
using Prixo.Application.Features.Ipd;
using Prixo.Application.Features.Lab;
using Prixo.Application.Features.Rad;
using Prixo.Domain.Entities.Billing;
using Prixo.Domain.Enums;
using Prixo.Domain.Exceptions;

namespace Prixo.Application.Features.Portal;

/// <summary>
/// Portal Records (plan §21: "Lab Reports &amp; Radiology Reports (approved-only PDFs),
/// Prescriptions, Bills &amp; receipts, Discharge Summaries, Medical History"). Every PDF here
/// is generated by the exact same method the staff screens use (LabOrderService/RadOrderService/
/// BillingService/DischargeService already gate on approval) — this class only adds the
/// patient-ownership check before calling them, plus a handful of small list queries those
/// services don't already expose at "everything for one patient" granularity. Medical History
/// reuses EMR's HistoryService outright.
/// </summary>
public class PortalRecordsService(
    IAppDbContext db, IPortalCurrentUser currentUser, IActivityLogger activity, TimeProvider timeProvider,
    LabOrderService labOrders, RadOrderService radOrders, BillingService billing, DischargeService discharge, HistoryService history)
{
    // ── Lab reports ──────────────────────────────────────────────────────────
    public async Task<IReadOnlyList<PortalLabOrderDto>> GetLabOrdersAsync(CancellationToken ct = default) =>
        await db.LabOrders.AsNoTracking().Where(o => o.PatientId == currentUser.PatientId)
            .OrderByDescending(o => o.OrderDate)
            .Select(o => new PortalLabOrderDto(o.Id, o.OrderNumber, o.OrderDate,
                o.Items.Any(i => i.Status == LabOrderItemStatus.Approved)))
            .ToListAsync(ct);

    public async Task<byte[]> GetLabReportPdfAsync(long orderId, CancellationToken ct = default)
    {
        await RequireOwnedAsync(db.LabOrders.Where(o => o.Id == orderId && o.PatientId == currentUser.PatientId), nameof(orderId), ct);
        return await labOrders.GenerateReportAsync(orderId, ct);
    }

    // ── Radiology reports ────────────────────────────────────────────────────
    public async Task<IReadOnlyList<PortalRadOrderItemDto>> GetRadOrderItemsAsync(CancellationToken ct = default) =>
        await db.RadOrderItems.AsNoTracking().Where(i => i.RadOrder!.PatientId == currentUser.PatientId)
            .Include(i => i.RadiologyTest).Include(i => i.RadOrder)
            .OrderByDescending(i => i.RadOrder!.OrderDate)
            .Select(i => new PortalRadOrderItemDto(i.Id, i.AccessionNumber, i.RadiologyTest!.Name, i.RadOrder!.OrderDate, i.Status == RadOrderItemStatus.Approved))
            .ToListAsync(ct);

    public async Task<byte[]> GetRadReportPdfAsync(long itemId, CancellationToken ct = default)
    {
        await RequireOwnedAsync(db.RadOrderItems.Where(i => i.Id == itemId && i.RadOrder!.PatientId == currentUser.PatientId), nameof(itemId), ct);
        return await radOrders.GenerateReportPdfAsync(itemId, ct);
    }

    // ── Prescriptions ────────────────────────────────────────────────────────
    public async Task<IReadOnlyList<PortalPrescriptionDto>> GetPrescriptionsAsync(CancellationToken ct = default) =>
        await db.Prescriptions.AsNoTracking().Where(p => p.Visit!.PatientId == currentUser.PatientId)
            .Include(p => p.Visit).ThenInclude(v => v!.Doctor).ThenInclude(d => d!.User)
            .Include(p => p.Items).ThenInclude(i => i.Drug)
            .OrderByDescending(p => p.Visit!.VisitDate)
            .Select(p => new PortalPrescriptionDto(p.Id, p.Visit!.VisitDate, p.Visit.Doctor!.User!.FullName,
                p.Items.Select(i => $"{i.Drug!.Name} — {i.Dose} {i.Frequency} for {i.Duration}").ToList()))
            .ToListAsync(ct);

    // ── Bills & receipts ─────────────────────────────────────────────────────
    public async Task<IReadOnlyList<PortalBillDto>> GetBillsAsync(CancellationToken ct = default) =>
        await db.Bills.AsNoTracking().Where(b => b.PatientId == currentUser.PatientId)
            .OrderByDescending(b => b.BillDate)
            .Select(b => new PortalBillDto(b.Id, b.BillNumber, b.BillDate, b.TotalAmount, b.BalanceAmount, b.Status.ToString()))
            .ToListAsync(ct);

    public async Task<byte[]> GetBillReceiptPdfAsync(long billId, CancellationToken ct = default)
    {
        await RequireOwnedAsync(db.Bills.Where(b => b.Id == billId && b.PatientId == currentUser.PatientId), nameof(billId), ct);
        return await billing.GenerateReceiptAsync(billId, null, ct);
    }

    /// <summary>
    /// "Payment (placeholder — gateway held)" (plan §21). No gateway is wired up, so this just
    /// queues intent for the billing desk — see OnlinePaymentRequest's doc comment.
    /// </summary>
    public async Task<OnlinePaymentRequestedDto> RequestOnlinePaymentAsync(long billId, CancellationToken ct = default)
    {
        var bill = await db.Bills.FirstOrDefaultAsync(b => b.Id == billId && b.PatientId == currentUser.PatientId, ct)
            ?? throw new DomainException($"No such bill for this patient ({nameof(billId)}).");
        if (bill.BalanceAmount <= 0)
        {
            throw new DomainException("This bill has no outstanding balance.");
        }

        var now = timeProvider.GetUtcNow();
        var request = new OnlinePaymentRequest { BillId = billId, PatientId = currentUser.PatientId, Amount = bill.BalanceAmount, RequestedAt = now };
        db.OnlinePaymentRequests.Add(request);
        await activity.LogAsync(ActivityEvents.PortalOnlinePaymentRequested, $"Online payment requested for bill {bill.BillNumber}", ct: ct);
        await db.SaveChangesAsync(ct);
        return new OnlinePaymentRequestedDto(request.Id, request.Amount, request.RequestedAt);
    }

    // ── Discharge summaries ──────────────────────────────────────────────────
    public async Task<IReadOnlyList<PortalDischargeSummaryDto>> GetDischargeSummariesAsync(CancellationToken ct = default) =>
        await db.Admissions.AsNoTracking()
            .Where(a => a.PatientId == currentUser.PatientId && a.DischargedAt != null)
            .Join(db.DischargeSummaries.Where(s => s.IsApproved), a => a.Id, s => s.AdmissionId, (a, s) => new { a, s })
            .OrderByDescending(x => x.a.DischargedAt)
            .Select(x => new PortalDischargeSummaryDto(x.a.Id, x.a.AdmissionNumber, x.a.DischargedAt!.Value, x.s.FinalDiagnosis))
            .ToListAsync(ct);

    public async Task<byte[]> GetDischargeSummaryPdfAsync(long admissionId, CancellationToken ct = default)
    {
        await RequireOwnedAsync(db.Admissions.Where(a => a.Id == admissionId && a.PatientId == currentUser.PatientId), nameof(admissionId), ct);
        return await discharge.GenerateDischargeSummaryPdfAsync(admissionId, ct);
    }

    // ── Medical history (portal-safe subset) ─────────────────────────────────
    public Task<IReadOnlyList<MedicalHistoryDto>> GetMedicalHistoryAsync(CancellationToken ct = default) => history.GetMedicalHistoryAsync(currentUser.PatientId, ct);
    public Task<IReadOnlyList<SurgicalHistoryDto>> GetSurgicalHistoryAsync(CancellationToken ct = default) => history.GetSurgicalHistoryAsync(currentUser.PatientId, ct);
    public Task<IReadOnlyList<AllergyDto>> GetAllergiesAsync(CancellationToken ct = default) => history.GetAllergiesAsync(currentUser.PatientId, true, ct);
    public Task<IReadOnlyList<ImmunizationDto>> GetImmunizationsAsync(CancellationToken ct = default) => history.GetImmunizationsAsync(currentUser.PatientId, ct);

    private static async Task RequireOwnedAsync<T>(IQueryable<T> ownedQuery, string idParamName, CancellationToken ct)
    {
        if (!await ownedQuery.AnyAsync(ct))
        {
            throw new DomainException($"No such record for this patient ({idParamName}).");
        }
    }
}
